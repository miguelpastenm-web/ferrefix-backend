-- Órdenes de compra (carrito -> orden), sus ítems y las cotizaciones.
-- Los precios, subtotales y total de una orden los calcula SIEMPRE el servidor con el catálogo.

CREATE TABLE ORDENES (
    ID                NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID        NUMBER(19,0)       NOT NULL,
    -- Copia de los datos del cliente al comprar (salen del token): la historia no cambia si edita su perfil.
    CLIENTE_RUT       VARCHAR2(12 CHAR)  NOT NULL,
    CLIENTE_NOMBRE    VARCHAR2(120 CHAR) NOT NULL,
    CLIENTE_EMAIL     VARCHAR2(120 CHAR) NOT NULL,
    TELEFONO_CONTACTO VARCHAR2(20 CHAR)  NOT NULL,
    DIRECCION_ENVIO   VARCHAR2(200 CHAR) NOT NULL,
    REGION_ENVIO      VARCHAR2(80 CHAR)  NOT NULL,
    COMUNA_ENVIO      VARCHAR2(80 CHAR)  NOT NULL,
    INDICACIONES      VARCHAR2(500 CHAR),
    METODO_PAGO       VARCHAR2(20 CHAR)  NOT NULL,
    SUBTOTAL          NUMBER(12,0)       NOT NULL,
    COSTO_ENVIO       NUMBER(10,0)       NOT NULL,
    TOTAL             NUMBER(12,0)       NOT NULL,
    ESTADO            VARCHAR2(20 CHAR)  NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ORDENES PRIMARY KEY (ID),
    CONSTRAINT FK_ORDENES_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID),
    CONSTRAINT CK_ORDENES_SUBTOTAL CHECK (SUBTOTAL > 0),
    CONSTRAINT CK_ORDENES_ENVIO CHECK (COSTO_ENVIO >= 0),
    CONSTRAINT CK_ORDENES_TOTAL CHECK (TOTAL = SUBTOTAL + COSTO_ENVIO),
    CONSTRAINT CK_ORDENES_METODO_PAGO CHECK (METODO_PAGO IN ('WEBPAY_DEBITO', 'TARJETA_CREDITO', 'TRANSFERENCIA')),
    CONSTRAINT CK_ORDENES_ESTADO CHECK (ESTADO IN ('PAGADA', 'EN_PREPARACION', 'DESPACHADA', 'ENTREGADA', 'CANCELADA'))
);

CREATE INDEX IX_ORDENES_USUARIO ON ORDENES (USUARIO_ID, CREATED_AT);
CREATE INDEX IX_ORDENES_ESTADO ON ORDENES (ESTADO);

CREATE TABLE ORDEN_ITEMS (
    ID              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    ORDEN_ID        NUMBER(19,0)       NOT NULL,
    PRODUCTO_ID     NUMBER(19,0),                -- NULL si el producto se eliminó después: el ítem conserva sku, nombre y precio
    SKU             VARCHAR2(30 CHAR)  NOT NULL,
    NOMBRE          VARCHAR2(150 CHAR) NOT NULL,
    PRECIO_UNITARIO NUMBER(10,0)       NOT NULL,
    CANTIDAD        NUMBER(5,0)        NOT NULL,
    SUBTOTAL        NUMBER(12,0)       NOT NULL,
    CONSTRAINT PK_ORDEN_ITEMS PRIMARY KEY (ID),
    CONSTRAINT FK_ORDEN_ITEMS_ORDEN FOREIGN KEY (ORDEN_ID) REFERENCES ORDENES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ORDEN_ITEMS_PRODUCTO FOREIGN KEY (PRODUCTO_ID) REFERENCES PRODUCTOS (ID) ON DELETE SET NULL,
    CONSTRAINT UK_ORDEN_ITEMS_ORDEN_SKU UNIQUE (ORDEN_ID, SKU),
    CONSTRAINT CK_ORDEN_ITEMS_PRECIO CHECK (PRECIO_UNITARIO > 0),
    CONSTRAINT CK_ORDEN_ITEMS_CANTIDAD CHECK (CANTIDAD BETWEEN 1 AND 1000),
    CONSTRAINT CK_ORDEN_ITEMS_SUBTOTAL CHECK (SUBTOTAL = PRECIO_UNITARIO * CANTIDAD)
);

CREATE INDEX IX_ORDEN_ITEMS_PRODUCTO ON ORDEN_ITEMS (PRODUCTO_ID);

CREATE TABLE COTIZACIONES (
    ID            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID    NUMBER(19,0),                  -- NULL si la pidió un visitante sin sesión
    NOMBRE        VARCHAR2(80 CHAR)   NOT NULL,
    RUT           VARCHAR2(12 CHAR)   NOT NULL,
    EMAIL         VARCHAR2(120 CHAR)  NOT NULL,
    TELEFONO      VARCHAR2(20 CHAR)   NOT NULL,
    TIPO_PROYECTO VARCHAR2(60 CHAR)   NOT NULL,
    REGION        VARCHAR2(80 CHAR)   NOT NULL,
    DETALLE       VARCHAR2(2000 CHAR) NOT NULL,
    DESPACHO_OBRA NUMBER(1,0) DEFAULT 1 NOT NULL,
    ESTADO        VARCHAR2(20 CHAR)   NOT NULL,
    NOTA_ADMIN    VARCHAR2(1000 CHAR),
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_COTIZACIONES PRIMARY KEY (ID),
    CONSTRAINT FK_COTIZACIONES_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID) ON DELETE SET NULL,
    CONSTRAINT CK_COTIZACIONES_DESPACHO CHECK (DESPACHO_OBRA IN (0, 1)),
    -- Los mismos 6 textos del selector del formulario de ferrefix-ui
    CONSTRAINT CK_COTIZACIONES_TIPO CHECK (TIPO_PROYECTO IN (
        'Herramientas de Alto Rendimiento', 'Materiales de Obra Gruesa', 'Fijaciones y Tornillería por Mayor',
        'Arriendo de Maquinaria y Demoledores', 'Equipamiento de Seguridad y Faena', 'Otro Requerimiento Especial')),
    CONSTRAINT CK_COTIZACIONES_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'EN_REVISION', 'RESPONDIDA', 'CERRADA'))
);

CREATE INDEX IX_COTIZACIONES_ESTADO ON COTIZACIONES (ESTADO, CREATED_AT);
CREATE INDEX IX_COTIZACIONES_USUARIO ON COTIZACIONES (USUARIO_ID);
