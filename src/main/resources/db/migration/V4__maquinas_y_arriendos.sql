-- Modelos de máquinas, sus unidades físicas, especificaciones y arriendos (cada arriendo apunta a UNA unidad).

CREATE TABLE MAQUINAS (
    ID          NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    CODIGO      VARCHAR2(30 CHAR)  NOT NULL,
    NOMBRE      VARCHAR2(150 CHAR) NOT NULL,
    MARCA       VARCHAR2(60 CHAR)  NOT NULL,
    CATEGORIA   VARCHAR2(60 CHAR)  NOT NULL,
    TARIFA_DIA  NUMBER(10,0)       NOT NULL,
    ESTADO      VARCHAR2(20 CHAR)  NOT NULL,
    INCLUYE     VARCHAR2(500 CHAR),
    IMAGEN_URL  VARCHAR2(300 CHAR),
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MAQUINAS PRIMARY KEY (ID),
    CONSTRAINT UK_MAQUINAS_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_MAQUINAS_TARIFA CHECK (TARIFA_DIA > 0),
    -- DISPONIBLE = queda al menos una unidad libre; NO_DISPONIBLE = ninguna (lo mantiene el servicio)
    CONSTRAINT CK_MAQUINAS_ESTADO CHECK (ESTADO IN ('DISPONIBLE', 'NO_DISPONIBLE'))
);

CREATE TABLE MAQUINA_UNIDADES (
    ID         NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    MAQUINA_ID NUMBER(19,0)      NOT NULL,
    CODIGO     VARCHAR2(40 CHAR) NOT NULL,
    ESTADO     VARCHAR2(20 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MAQUINA_UNIDADES PRIMARY KEY (ID),
    CONSTRAINT FK_UNIDADES_MAQUINA FOREIGN KEY (MAQUINA_ID) REFERENCES MAQUINAS (ID) ON DELETE CASCADE,
    CONSTRAINT UK_UNIDADES_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_UNIDADES_ESTADO CHECK (ESTADO IN ('DISPONIBLE', 'ARRENDADA'))
);

CREATE INDEX IX_UNIDADES_MAQUINA_ESTADO ON MAQUINA_UNIDADES (MAQUINA_ID, ESTADO);

CREATE TABLE MAQUINA_ESPECIFICACIONES (
    ID         NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    MAQUINA_ID NUMBER(19,0)       NOT NULL,
    CLAVE      VARCHAR2(80 CHAR)  NOT NULL,
    VALOR      VARCHAR2(300 CHAR) NOT NULL,
    ORDEN      NUMBER(3,0)        NOT NULL,
    CONSTRAINT PK_MAQUINA_ESPECIFICACIONES PRIMARY KEY (ID),
    CONSTRAINT FK_MAQESPEC_MAQUINA FOREIGN KEY (MAQUINA_ID) REFERENCES MAQUINAS (ID) ON DELETE CASCADE,
    CONSTRAINT UK_MAQESPEC_MAQUINA_CLAVE UNIQUE (MAQUINA_ID, CLAVE)
);

CREATE TABLE ARRIENDOS (
    ID                NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    UNIDAD_ID         NUMBER(19,0)       NOT NULL,
    USUARIO_ID        NUMBER(19,0)       NOT NULL,
    TARIFA_DIA        NUMBER(10,0)       NOT NULL,   -- copia de la tarifa al contratar (no cambia si el modelo sube de precio)
    DIAS              NUMBER(3,0)        NOT NULL,
    FECHA_INICIO      DATE               NOT NULL,
    FECHA_FIN         DATE               NOT NULL,   -- último día de arriendo, inclusive = inicio + días - 1
    TOTAL             NUMBER(12,0)       NOT NULL,
    TELEFONO_CONTACTO VARCHAR2(20 CHAR)  NOT NULL,
    DIRECCION_FAENA   VARCHAR2(200 CHAR) NOT NULL,
    REGION_FAENA      VARCHAR2(80 CHAR)  NOT NULL,
    COMUNA_FAENA      VARCHAR2(80 CHAR)  NOT NULL,
    ESTADO            VARCHAR2(20 CHAR)  NOT NULL,
    FECHA_DEVOLUCION  TIMESTAMP,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ARRIENDOS PRIMARY KEY (ID),
    CONSTRAINT FK_ARRIENDOS_UNIDAD FOREIGN KEY (UNIDAD_ID) REFERENCES MAQUINA_UNIDADES (ID),
    CONSTRAINT FK_ARRIENDOS_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID),
    CONSTRAINT CK_ARRIENDOS_TARIFA CHECK (TARIFA_DIA > 0),
    CONSTRAINT CK_ARRIENDOS_DIAS CHECK (DIAS BETWEEN 1 AND 90),
    CONSTRAINT CK_ARRIENDOS_FECHAS CHECK (FECHA_FIN >= FECHA_INICIO),
    CONSTRAINT CK_ARRIENDOS_TOTAL CHECK (TOTAL = TARIFA_DIA * DIAS),
    CONSTRAINT CK_ARRIENDOS_ESTADO CHECK (ESTADO IN ('VIGENTE', 'FINALIZADO')),
    CONSTRAINT CK_ARRIENDOS_DEVOLUCION CHECK (
        (ESTADO = 'FINALIZADO' AND FECHA_DEVOLUCION IS NOT NULL)
        OR (ESTADO = 'VIGENTE' AND FECHA_DEVOLUCION IS NULL))
);

CREATE INDEX IX_ARRIENDOS_USUARIO ON ARRIENDOS (USUARIO_ID);
CREATE INDEX IX_ARRIENDOS_UNIDAD ON ARRIENDOS (UNIDAD_ID);

-- Índice único PARCIAL: como máximo UN arriendo VIGENTE por unidad. Oracle no indexa las filas donde la
-- expresión es NULL (arriendos FINALIZADOS), así que solo restringe a los vigentes. Es la red de seguridad
-- final de la base ante cualquier carrera que se escape al bloqueo del servicio.
CREATE UNIQUE INDEX UX_ARRIENDOS_UNIDAD_VIGENTE
    ON ARRIENDOS (CASE WHEN ESTADO = 'VIGENTE' THEN UNIDAD_ID END);
