CREATE TABLE PRODUCTOS (
    ID                NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    SKU               VARCHAR2(30 CHAR)   NOT NULL,
    NOMBRE            VARCHAR2(150 CHAR)  NOT NULL,
    MARCA             VARCHAR2(60 CHAR)   NOT NULL,
    CATEGORIA         VARCHAR2(40 CHAR)   NOT NULL,
    PRECIO_VENTA      NUMBER(10,0)        NOT NULL,
    STOCK             NUMBER(10,0)        DEFAULT 0 NOT NULL,
    ESTADO            VARCHAR2(20 CHAR)   NOT NULL,
    IMAGEN_URL        VARCHAR2(300 CHAR),
    IMAGEN_OFERTA_URL VARCHAR2(300 CHAR),
    DESCRIPCION       VARCHAR2(2000 CHAR),
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PRODUCTOS PRIMARY KEY (ID),
    CONSTRAINT UK_PRODUCTOS_SKU UNIQUE (SKU),
    CONSTRAINT CK_PRODUCTOS_PRECIO CHECK (PRECIO_VENTA > 0),
    CONSTRAINT CK_PRODUCTOS_STOCK CHECK (STOCK >= 0),
    CONSTRAINT CK_PRODUCTOS_ESTADO CHECK (ESTADO IN ('DISPONIBLE', 'AGOTADO')),
    -- Invariante: el estado siempre refleja el stock (0 = AGOTADO, >0 = DISPONIBLE)
    CONSTRAINT CK_PRODUCTOS_ESTADO_STOCK CHECK (
        (STOCK = 0 AND ESTADO = 'AGOTADO') OR (STOCK > 0 AND ESTADO = 'DISPONIBLE')),
    CONSTRAINT CK_PRODUCTOS_CATEGORIA CHECK (CATEGORIA IN (
        'Construcción', 'Maderas', 'Herramientas', 'Fijaciones', 'Gasfitería',
        'Electricidad', 'Pinturas', 'Cerámicas', 'Seguridad'))
);

CREATE INDEX IX_PRODUCTOS_CATEGORIA ON PRODUCTOS (CATEGORIA);

CREATE TABLE PRODUCTO_ESPECIFICACIONES (
    ID          NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    PRODUCTO_ID NUMBER(19,0)       NOT NULL,
    CLAVE       VARCHAR2(80 CHAR)  NOT NULL,
    VALOR       VARCHAR2(300 CHAR) NOT NULL,
    ORDEN       NUMBER(3,0)        NOT NULL,
    CONSTRAINT PK_PRODUCTO_ESPECIFICACIONES PRIMARY KEY (ID),
    CONSTRAINT FK_PRODESPEC_PRODUCTO FOREIGN KEY (PRODUCTO_ID) REFERENCES PRODUCTOS (ID) ON DELETE CASCADE,
    CONSTRAINT UK_PRODESPEC_PRODUCTO_CLAVE UNIQUE (PRODUCTO_ID, CLAVE)
);
