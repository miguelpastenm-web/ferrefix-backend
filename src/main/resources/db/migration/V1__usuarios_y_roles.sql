CREATE TABLE USUARIOS (
    ID            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    RUT           VARCHAR2(12 CHAR)  NOT NULL,
    NOMBRE        VARCHAR2(120 CHAR) NOT NULL,
    EMAIL         VARCHAR2(120 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(100 CHAR) NOT NULL,
    TELEFONO      VARCHAR2(20 CHAR),
    DIRECCION     VARCHAR2(200 CHAR),
    REGION        VARCHAR2(80 CHAR),
    COMUNA        VARCHAR2(80 CHAR),
    ACTIVO        NUMBER(1,0) DEFAULT 1 NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIOS_RUT UNIQUE (RUT),
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE USUARIO_ROLES (
    USUARIO_ID NUMBER(19,0)      NOT NULL,
    ROL        VARCHAR2(20 CHAR) NOT NULL,
    CONSTRAINT PK_USUARIO_ROLES PRIMARY KEY (USUARIO_ID, ROL),
    CONSTRAINT FK_USUARIO_ROLES_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_USUARIO_ROLES_ROL CHECK (ROL IN ('ADMIN', 'CLIENTE'))
);
